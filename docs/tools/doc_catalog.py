#!/usr/bin/env python3
"""Ordered documentation catalog shared by source indexes and Doxygen."""
import argparse
from functools import lru_cache
import json
import os
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]

# Pages that carry both languages in one file and need no original-language tag.
BILINGUAL_PAGES = {'docs/README.md', 'examples-python/README.md'}


@lru_cache(maxsize=1)
def categories():
    return json.loads((ROOT / 'docs/catalog.json').read_text())['categories']


def localized(source, language):
    source = Path(source)
    stem = source.stem.removesuffix('_zh')
    candidate = source.with_name(stem + ('_zh' if language == 'zh' else '') + '.md')
    return candidate if candidate.is_file() else source


def title(source):
    heading = next(line[2:] for line in Path(source).read_text().splitlines() if line.startswith('# '))
    return re.sub(r'\s*\{#[^}]+\}', '', heading).strip()


def entries():
    return [page for category in categories() for group in category['groups'] for page in group['pages']]


def sources(language):
    return {localized(ROOT / item['source'], language)
            for item in [*categories(), *entries()]}


def children(source, language):
    source = source.resolve()
    if source in (ROOT / 'docs/00_mainpage.md', ROOT / 'docs/00_mainpage_zh.md'):
        return {localized(ROOT / c['source'], language) for c in categories()}
    for category in categories():
        if source == localized(ROOT / category['source'], language):
            return {localized(ROOT / p['source'], language)
                    for group in category['groups'] for p in group['pages']}
    return set()


def index_text(category, language):
    path = ROOT / category['source']
    other = 'en' if language == 'zh' else 'zh'
    target = 'index.md' if other == 'en' else 'index_zh.md'
    label = 'English' if other == 'en' else '中文'
    lines = [f"# {category['title'][language]} {{#{category['page_id']}}}", '',
             '<!-- Generated from docs/catalog.json by docs/tools/doc_catalog.py --write. -->', '',
             f'[{label}]({target})', '', category['description'][language], '']
    for group in category['groups']:
        lines.extend(['## ' + group['title'][language], ''])
        for page in group['pages']:
            source = localized(ROOT / page['source'], language)
            name = title(source)
            if page['source'] not in BILINGUAL_PAGES:
                zh_source = localized(ROOT / page['source'], 'zh')
                if language == 'en' and source.stem.endswith('_zh'):
                    name += ' (Chinese original)'
                elif language == 'zh' and not zh_source.stem.endswith('_zh'):
                    name += ' (英文原文)'
            lines.append(f'- [{name}]({os.path.relpath(source, path.parent)})')
        lines.append('')
    return '\n'.join(lines)


def doxygen_inputs(language):
    paths = sorted(sources(language))
    return "# Generated by docs/tools/doc_catalog.py --write\n" + "".join(
        "INPUT += ../" + str(p.relative_to(ROOT)) + "\n" for p in paths)


def check():
    errors = []
    seen, slugs = set(), set()
    for item in [*categories(), *entries()]:
        source = ROOT / item['source']
        if not source.is_file():
            errors.append(f'missing catalog source: {source.relative_to(ROOT)}')
        localized_sources = {localized(source, language) for language in ('en', 'zh')}
        if localized_sources & seen:
            errors.append(f'duplicate catalog source: {source.relative_to(ROOT)}')
        seen.update(localized_sources)
        slug = item.get('slug', item['id'] + '/index' if 'id' in item else '')
        if slug in slugs:
            errors.append(f'duplicate manual URL: {slug}')
        slugs.add(slug)
    for category in categories():
        directory = ROOT / 'docs' / category['id']
        for source in directory.rglob('*.md'):
            if localized(source, 'en') not in seen:
                errors.append(f'unclassified document: {source.relative_to(ROOT)}')
        for language in ('en', 'zh'):
            source = Path(category['source'])
            if language == 'zh':source = source.with_name('index_zh.md')
            path = ROOT / source
            if not path.is_file() or path.read_text() != index_text(category, language):
                errors.append(f'stale index: {source}; run python3 docs/tools/doc_catalog.py --write')
    for language in ("en", "zh"):
        path = ROOT / f"docs/catalog.{language}.doxy"
        if not path.exists() or path.read_text() != doxygen_inputs(language):
            errors.append(f"stale Doxygen input list: {path.name}; run --write")
    return errors


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    if args.write:
        for category in categories():
            for language in ('en', 'zh'):
                path = ROOT / category['source']
                if language == 'zh':path = path.with_name('index_zh.md')
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(index_text(category, language))
        for language in ("en", "zh"):
            (ROOT / f"docs/catalog.{language}.doxy").write_text(doxygen_inputs(language))
    errors = check()
    if errors:raise SystemExit('\n'.join(errors))
    print(f'Documentation catalog: {len(categories())} sections, {len(entries())} uniquely classified documents')

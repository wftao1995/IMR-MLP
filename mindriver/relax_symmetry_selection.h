#pragma once
#include "external/spglib_driver.h"
#include <string>
#include <vector>

namespace RelaxSymmetry {
// Select only operations present in the initial mapped dataset. Identity is
// retained and requested generators are closed under composition modulo lattice
// translations. Operation indices always refer to that initial dataset.
struct InitialSelection {
    Symmetry3D::symdataset positions, cell;
    std::vector<int> operations, cell_operations, sites;
    bool site_only = false;
};

// Empty operation text preserves the complete initial group. Empty site text
// preserves global orbit constraints. With explicit sites, all other atoms are
// free, and the cell uses only the group generated by stabilizers of the listed
// sites. This does not impose unused global operations on a site-only request.
InitialSelection select_initial(const Symmetry3D::symdataset &dataset,
                                const std::string &operations,
                                const std::string &sites);
}
